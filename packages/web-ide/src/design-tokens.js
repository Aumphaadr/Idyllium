/** Значение токена темы: token('dark', 'syntax-keyword') → '#b892ff'. */
export function token(theme, name) {
  const table = DESIGN_TOKENS[theme === 'light' ? 'light' : 'dark'];
  if (!(name in table)) throw new Error('design token is missing: ' + name);
  return table[name];
}
