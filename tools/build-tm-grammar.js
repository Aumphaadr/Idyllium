#!/usr/bin/env node
'use strict';

// Генератор TextMate-грамматики VS Code из словарей подсветки Web IDE.
// Единственный источник правды — packages/web-ide/src/idyllium-highlight.js
// (те же KEYWORDS/BUILTIN_TYPES/CLASS_NAMES/QUALIFIED_TYPES, что питают
// Monarch-токенизатор Monaco): раньше грамматика жила отдельной копией и
// отстала от языка на несколько библиотек. Логика правил повторяет
// Monarch-токенизатор, чтобы базовая раскраска в VS Code совпадала с Web IDE
// (поверх обоих ложатся одни и те же семантические токены компилятора).
//
// Запуск: node tools/build-tm-grammar.js [--check]
//   --check: не писать файл, а сверить с лежащим в репозитории (страж).

const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const grammarPath = path.join(rootDir, 'packages', 'vscode-idyllium', 'syntaxes', 'idyllium.tmLanguage.json');

async function loadDictionaries() {
  const highlight = await import(
    'file://' + path.join(rootDir, 'packages', 'web-ide', 'src', 'idyllium-highlight.js')
  );
  return {
    keywords: [...highlight.KEYWORDS],
    builtinTypes: [...highlight.BUILTIN_TYPES],
    classNames: [...highlight.CLASS_NAMES],
    qualifiedTypes: [...highlight.QUALIFIED_TYPES],
  };
}

const IDENT = '[\\p{L}_][\\p{L}\\p{N}_]*';
const UPPER_IDENT = '[A-ZА-ЯЁ][\\p{L}\\p{N}_]*';
// Та же эвристика типовой позиции, что в Monarch и легаси-подсветке:
// СловоСЗаглавной перед «имя, а дальше = ; , ) [ или конец строки».
const TYPE_POSITION_LOOKAHEAD = `(?=\\s+${IDENT}\\s*(?:[=;,)\\[]|$))`;

function alternation(words) {
  return [...words].sort().join('|');
}

function buildGrammar({ keywords, builtinTypes, classNames, qualifiedTypes }) {
  // Группы ключевых слов — семантичные скоупы для чужих тем VS Code;
  // фирменные темы Idyllium красят все группы одним цветом, как Monaco.
  const keywordGroups = {
    'keyword.control.idyllium': ['if', 'else', 'while', 'do', 'for', 'break', 'continue', 'return', 'try', 'catch', 'finally', 'use'],
    'keyword.operator.logical.idyllium': ['and', 'or', 'xor', 'not'],
    'constant.language.idyllium': ['true', 'false', 'null'],
    'variable.language.idyllium': ['this', 'parent'],
    'keyword.declaration.idyllium': ['class', 'const', 'constructor', 'contract', 'event', 'extends', 'function', 'private', 'public', 'static'],
  };
  const grouped = Object.values(keywordGroups).flat().sort();
  const expected = [...keywords].sort();
  if (JSON.stringify(grouped) !== JSON.stringify(expected)) {
    throw new Error(
      'keyword groups drifted from KEYWORDS:\n  groups: ' + grouped.join(' ') + '\n  source: ' + expected.join(' '),
    );
  }

  const qualifiedAlternation = alternation(qualifiedTypes);
  return {
    $comment: 'GENERATED by tools/build-tm-grammar.js from packages/web-ide/src/idyllium-highlight.js — do not edit by hand.',
    $schema: 'https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json',
    name: 'Idyllium',
    scopeName: 'source.idyllium',
    patterns: [
      { include: '#comments' },
      { include: '#strings' },
      { include: '#numbers' },
      { include: '#useStatements' },
      { include: '#classDeclarations' },
      { include: '#memberAccess' },
      { include: '#keywords' },
      { include: '#types' },
      { include: '#functions' },
      { include: '#identifiers' },
      { include: '#operators' },
      { include: '#punctuation' },
    ],
    repository: {
      comments: {
        patterns: [
          { name: 'comment.block.idyllium', begin: '/\\*', end: '\\*/' },
          { name: 'comment.line.double-slash.idyllium', match: '//.*$' },
        ],
      },
      strings: {
        // Однострочные match-правила, как в Monaco: незакрытая кавычка не
        // должна перекрашивать «строкой» весь остаток файла.
        patterns: [
          {
            name: 'string.quoted.double.idyllium',
            match: '"(?:\\\\.|[^"\\\\])*"',
            captures: { 0: { patterns: [{ name: 'constant.character.escape.idyllium', match: '\\\\.' }] } },
          },
          {
            name: 'string.quoted.single.idyllium',
            match: "'(?:\\\\.|[^'\\\\])*'",
            captures: { 0: { patterns: [{ name: 'constant.character.escape.idyllium', match: '\\\\.' }] } },
          },
        ],
      },
      numbers: {
        patterns: [
          { name: 'constant.numeric.idyllium', match: '\\b\\d+(?:\\.\\d+)?\\b' },
        ],
      },
      useStatements: {
        patterns: [
          {
            match: `\\b(use)\\s+(${IDENT})`,
            captures: {
              1: { name: 'keyword.control.import.idyllium' },
              2: { name: 'entity.name.namespace.idyllium' },
            },
          },
        ],
      },
      classDeclarations: {
        patterns: [
          {
            match: `\\b(class|extends)\\s+(${IDENT})`,
            captures: {
              1: { name: 'keyword.declaration.idyllium' },
              2: { name: 'entity.name.type.class.idyllium' },
            },
          },
        ],
      },
      memberAccess: {
        // Повторяет состояние afterDot токенизатора Monaco.
        patterns: [
          {
            match: `(\\.)\\s*(${UPPER_IDENT})${TYPE_POSITION_LOOKAHEAD}`,
            captures: {
              1: { name: 'punctuation.accessor.idyllium' },
              2: { name: 'entity.name.type.class.idyllium' },
            },
          },
          {
            match: `(\\.)\\s*(${qualifiedAlternation})\\b(?=\\s*\\()`,
            captures: {
              1: { name: 'punctuation.accessor.idyllium' },
              2: { name: 'entity.name.type.class.idyllium' },
            },
          },
          {
            match: `(\\.)\\s*(${IDENT})(?=\\s*\\()`,
            captures: {
              1: { name: 'punctuation.accessor.idyllium' },
              2: { name: 'entity.name.function.member.idyllium' },
            },
          },
          {
            match: `(\\.)\\s*(${qualifiedAlternation})\\b`,
            captures: {
              1: { name: 'punctuation.accessor.idyllium' },
              2: { name: 'entity.name.type.class.idyllium' },
            },
          },
          {
            match: `(\\.)\\s*(${IDENT})`,
            captures: {
              1: { name: 'punctuation.accessor.idyllium' },
              2: { name: 'variable.other.member.idyllium' },
            },
          },
        ],
      },
      keywords: {
        patterns: Object.entries(keywordGroups).map(([scope, words]) => ({
          name: scope,
          match: `\\b(?:${alternation(words)})\\b`,
        })),
      },
      types: {
        patterns: [
          { name: 'storage.type.primitive.idyllium', match: `\\b(?:${alternation(builtinTypes)})\\b` },
          { name: 'entity.name.type.class.idyllium', match: `\\b(?:${alternation(classNames)})\\b` },
          { name: 'entity.name.type.class.idyllium', match: `\\b${UPPER_IDENT}${TYPE_POSITION_LOOKAHEAD}` },
        ],
      },
      functions: {
        patterns: [
          { name: 'entity.name.function.idyllium', match: `\\b${IDENT}(?=\\s*\\()` },
        ],
      },
      identifiers: {
        // Дефолт Monarch: любое оставшееся имя — «объект» (в фирменных
        // темах — голубой, чужие темы решают сами по variable.other).
        patterns: [
          { name: 'variable.other.idyllium', match: `\\b${IDENT}\\b` },
        ],
      },
      operators: {
        patterns: [
          { name: 'keyword.operator.idyllium', match: '==|!=|<=|>=|\\+=|-=|\\*=|/=|[+\\-*/<>=!~]' },
        ],
      },
      punctuation: {
        patterns: [
          { name: 'punctuation.idyllium', match: '[{}\\[\\]();,.:]' },
        ],
      },
    },
  };
}

async function main() {
  const grammar = buildGrammar(await loadDictionaries());
  const rendered = JSON.stringify(grammar, null, 2) + '\n';
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(grammarPath) ? fs.readFileSync(grammarPath, 'utf8') : '';
    if (current !== rendered) {
      console.error('idyllium.tmLanguage.json is out of date — run: node tools/build-tm-grammar.js');
      process.exit(1);
    }
    console.log('tm grammar is in sync');
    return;
  }
  fs.writeFileSync(grammarPath, rendered);
  console.log(`tm grammar written: ${path.relative(rootDir, grammarPath)}`);
}

main().catch((error) => {
  console.error(error.message || error);
  process.exit(1);
});
